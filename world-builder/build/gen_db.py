"""Build the service-system database from the generated population.

Emits DDL and a seed script in two dialects - SQLite for local development and
for the MCP server's test suite, and T-SQL for Azure SQL Database in the
deployed environment - plus a ready-to-use SQLite file.

The two dialects are generated from one templated schema, so the deployed
database and the one the tests run against cannot drift apart.

One table is deliberately wrong: TsbApplicability records TSB-C-0051 as ending
at serial 1500 when the bulletin document says 1850. That is trap 1, and it is
the single most important row in the database.

    .venv/Scripts/python.exe world-builder/build/gen_db.py
"""

from __future__ import annotations

import json
import sqlite3
from datetime import date, timedelta
from pathlib import Path

from adjudicate import ENTITIES, INSTRUMENTS, CATALOG

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "out" / "data"
OUT = ROOT / "out" / "db"

# Type map per dialect. SQLite is forgiving; Azure SQL is not - TEXT is
# deprecated in T-SQL and cannot carry a primary key or an index, and money
# wants DECIMAL rather than REAL.
TYPES = {
    "sqlite": {
        "ID": "TEXT", "NAME": "TEXT", "LONGTEXT": "TEXT", "DATE": "TEXT",
        "TS": "TEXT", "MONEY": "REAL", "PCT": "REAL", "HOURS": "REAL", "INT": "INTEGER",
    },
    "mssql": {
        "ID": "NVARCHAR(40)", "NAME": "NVARCHAR(200)", "LONGTEXT": "NVARCHAR(MAX)",
        "DATE": "DATE",
        # DATETIMEOFFSET, not DATETIME2: the action tools stamp rows in UTC and
        # an audit trail that does not record which zone it was written in is
        # worth very little. DATETIME2 has no offset component, so the "+00:00"
        # on the way in would be discarded silently.
        "TS": "DATETIMEOFFSET(0)",
        "MONEY": "DECIMAL(14,2)",
        "PCT": "DECIMAL(5,2)", "HOURS": "DECIMAL(6,2)", "INT": "INT",
    },
}

# Dates are written as ISO-8601 literals ('2026-06-18'). For DATE, DATETIME2 and
# DATETIMEOFFSET that format is language-neutral in T-SQL - it is interpreted the
# same way whatever SET DATEFORMAT or SET LANGUAGE is in force. The legacy
# DATETIME type does NOT have that guarantee, which is one reason it is not used
# here.

SCHEMA_TEMPLATE = """
-- Contoso Industrial service claim system
-- Generated by scenario/build/gen_db.py - do not edit by hand.
-- Dialect: {dialect}

DROP TABLE IF EXISTS ClaimAdjudicationDraft;
DROP TABLE IF EXISTS EvidenceRequest;
DROP TABLE IF EXISTS GoodwillEscalation;
DROP TABLE IF EXISTS TsbApplicability;
DROP TABLE IF EXISTS GoodwillAuthority;
DROP TABLE IF EXISTS ServiceHistory;
DROP TABLE IF EXISTS AssetTelemetry;
DROP TABLE IF EXISTS Claims;
DROP TABLE IF EXISTS Assets;
DROP TABLE IF EXISTS Parts;
DROP TABLE IF EXISTS Dealers;

CREATE TABLE Dealers (
    dealer_id            {ID} PRIMARY KEY,
    name                 {NAME} NOT NULL,
    region               {ID} NOT NULL,
    currency             {ID} NOT NULL,
    uplift_pct           {PCT} NOT NULL,
    agreement_ref        {ID} NOT NULL,
    submission_sla_days  {INT} NOT NULL
);

CREATE TABLE Parts (
    part_no        {ID} PRIMARY KEY,
    description    {NAME} NOT NULL,
    family         {ID} NOT NULL,
    component      {ID},
    supersedes     {ID},
    superseded_by  {ID},
    price_inr      {MONEY},
    price_eur      {MONEY},
    price_sgd      {MONEY}
);

CREATE TABLE Assets (
    serial              {ID} PRIMARY KEY,
    family              {ID} NOT NULL,
    dealer_id           {ID} NOT NULL REFERENCES Dealers(dealer_id),
    customer_id         {ID},
    customer_name       {NAME},
    site                {NAME},
    region              {ID} NOT NULL,
    install_date        {DATE},
    -- NULL for a small number of assets. Policy 2.3: coverage cannot be
    -- determined and install_date must not be substituted.
    commissioning_date  {DATE}
);

CREATE TABLE AssetTelemetry (
    serial         {ID} NOT NULL REFERENCES Assets(serial),
    as_of_date     {DATE} NOT NULL,
    running_hours  {INT} NOT NULL,
    PRIMARY KEY (serial, as_of_date)
);

CREATE TABLE Claims (
    claim_id              {ID} PRIMARY KEY,
    serial                {ID} NOT NULL,
    dealer_id             {ID} NOT NULL REFERENCES Dealers(dealer_id),
    submitted_date        {DATE} NOT NULL,
    repair_date           {DATE} NOT NULL,
    operation_code        {ID} NOT NULL,
    claimed_part          {ID},
    claimed_labour_hours  {HOURS} NOT NULL,
    goodwill_requested    {MONEY},
    status                {ID} NOT NULL
);

CREATE TABLE ServiceHistory (
    job_id          {ID} PRIMARY KEY,
    serial          {ID} NOT NULL REFERENCES Assets(serial),
    job_date        {DATE} NOT NULL,
    operation_code  {ID} NOT NULL,
    component       {ID},
    part_fitted     {ID},
    labour_hours    {HOURS},
    claim_id        {ID},
    completed_date  {DATE}
);

CREATE TABLE GoodwillAuthority (
    tier            {INT} PRIMARY KEY,
    max_amount_inr  {MONEY},
    approver_role   {NAME} NOT NULL
);

-- Reporting table. Maintained by hand and known to lag the bulletin documents.
-- Policy 1.4: where this table and a bulletin disagree, the bulletin governs.
CREATE TABLE TsbApplicability (
    tsb_id          {ID} PRIMARY KEY,
    family          {ID} NOT NULL,
    serial_from     {INT},
    serial_to       {INT},
    effective_from  {DATE},
    status          {ID}
);

-- Action tables. Everything the agent writes is a draft; nothing pays or sends.
CREATE TABLE ClaimAdjudicationDraft (
    draft_id          {ID} PRIMARY KEY,
    claim_id          {ID} NOT NULL,
    decision          {ID} NOT NULL,
    payable           {MONEY},
    currency          {ID},
    instrument_refs   {LONGTEXT},
    notes             {LONGTEXT},
    created_at        {TS} NOT NULL,
    created_by        {LONGTEXT}
);

CREATE TABLE EvidenceRequest (
    request_id   {ID} PRIMARY KEY,
    claim_id     {ID} NOT NULL,
    field_name   {ID} NOT NULL,
    reason       {LONGTEXT},
    created_at   {TS} NOT NULL
);

CREATE TABLE GoodwillEscalation (
    escalation_id  {ID} PRIMARY KEY,
    claim_id       {ID} NOT NULL,
    amount         {MONEY} NOT NULL,
    approver_role  {NAME} NOT NULL,
    created_at     {TS} NOT NULL,
    status         {ID} NOT NULL
);

CREATE INDEX idx_telemetry_serial ON AssetTelemetry(serial, as_of_date);
CREATE INDEX idx_history_serial   ON ServiceHistory(serial, job_date);
CREATE INDEX idx_claims_serial    ON Claims(serial);
"""


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(table: str, cols: list[str], rows: list[list]) -> str:
    if not rows:
        return ""
    out = [f"-- {table}: {len(rows)} rows"]
    for r in rows:
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES "
                   f"({', '.join(q(v) for v in r)});")
    return "\n".join(out) + "\n"


def schema(dialect: str) -> str:
    """Render the templated DDL for one dialect."""
    text = SCHEMA_TEMPLATE.replace("{dialect}", dialect)
    for token, sql_type in TYPES[dialect].items():
        text = text.replace("{" + token + "}", sql_type)
    if "{" in text.replace("{dialect}", ""):
        raise ValueError(f"unrendered token left in {dialect} schema")
    return text


def batched(statements: list[str], dialect: str, size: int = 500) -> str:
    """T-SQL wants GO separators for sqlcmd; SQLite wants none.

    Azure SQL will accept one enormous batch, but sqlcmd handles it far better
    in chunks, and a failure part-way through reports a usable line number.
    """
    nl = chr(10)
    if dialect != "mssql":
        return nl.join(statements)
    out, batch = [], []
    for stmt in statements:
        batch.append(stmt)
        if len(batch) >= size:
            out.append(nl.join(batch) + nl + "GO")
            batch = []
    if batch:
        out.append(nl.join(batch) + nl + "GO")
    return nl.join(out)


def build() -> tuple[str, dict[str, int]]:
    assets = json.loads((DATA / "assets.json").read_text(encoding="utf-8"))
    telemetry = json.loads((DATA / "telemetry.json").read_text(encoding="utf-8"))
    records = json.loads((DATA / "claims.json").read_text(encoding="utf-8"))
    customers = {c["customer_id"]: c for c in ENTITIES["customers"]}
    operations = {o["op_code"]: o for o in CATALOG["operations"]}

    sql: list[str] = []
    counts: dict[str, int] = {}

    # --- Dealers ------------------------------------------------------
    rows = [[d["dealer_id"], d["name"], d["region"], d["currency"],
             d["uplift_pct"], d["agreement_ref"], d["submission_sla_days"]]
            for d in ENTITIES["dealers"]]
    sql.append(insert("Dealers",
                      ["dealer_id", "name", "region", "currency", "uplift_pct",
                       "agreement_ref", "submission_sla_days"], rows))
    counts["Dealers"] = len(rows)

    # --- Parts --------------------------------------------------------
    rows = [[p["part_no"], p["description"], p["family"], p.get("component"),
             p.get("supersedes"), p.get("superseded_by"),
             p["price"]["INR"], p["price"]["EUR"], p["price"]["SGD"]]
            for p in CATALOG["parts"]]
    sql.append(insert("Parts",
                      ["part_no", "description", "family", "component", "supersedes",
                       "superseded_by", "price_inr", "price_eur", "price_sgd"], rows))
    counts["Parts"] = len(rows)

    # --- Assets -------------------------------------------------------
    rows = []
    for a in assets:
        if not a["known"]:
            continue                      # absent from the registry on purpose
        cust = customers.get(a["customer_id"], {})
        rows.append([a["serial"], a["family"], a["dealer_id"], a["customer_id"],
                     cust.get("name"), cust.get("site"), a["region"],
                     a["install_date"], a["commissioning_date"]])
    sql.append(insert("Assets",
                      ["serial", "family", "dealer_id", "customer_id", "customer_name",
                       "site", "region", "install_date", "commissioning_date"], rows))
    counts["Assets"] = len(rows)

    # --- Telemetry ----------------------------------------------------
    known = {a["serial"] for a in assets if a["known"]}
    rows = [[t["serial"], t["as_of_date"], t["running_hours"]]
            for t in telemetry if t["serial"] in known]
    sql.append(insert("AssetTelemetry", ["serial", "as_of_date", "running_hours"], rows))
    counts["AssetTelemetry"] = len(rows)

    # --- Claims -------------------------------------------------------
    rows = [[r["claim"]["claim_id"], r["claim"]["serial"], r["claim"]["dealer_id"],
             r["claim"]["submitted_date"], r["claim"]["repair_date"],
             r["claim"]["op_code"], r["claim"]["claimed_part"],
             r["claim"]["claimed_hours"], r["claim"].get("goodwill_requested"),
             "Submitted"]
            for r in records]
    # Earlier warranty claims that a repair-warranty claim (policy 6.1) rests on.
    # They are settled history, not claims to adjudicate, so they are seeded as
    # Paid and are not in claims.json. Their ids are C-2026-03xxx; the reset
    # scripts in scripts/ rely on that prefix to restore the seeded status.
    seen = {row[0] for row in rows}
    for r in records:
        c, prior = r["claim"], r["claim"].get("prior_claim")
        if not prior:
            continue
        if prior["claim_id"] in seen:
            raise ValueError(f"prior claim {prior['claim_id']} is cited twice or "
                             f"collides with a live claim")
        if not prior["claim_id"].startswith("C-2026-03"):
            raise ValueError(f"prior claim {prior['claim_id']} must use the C-2026-03xxx range")
        seen.add(prior["claim_id"])
        done = date.fromisoformat(prior["completed_date"])
        rows.append([prior["claim_id"], c["serial"], c["dealer_id"],
                     (done + timedelta(days=6)).isoformat(), prior["completed_date"],
                     c["op_code"], c["part_fitted"], c["claimed_hours"], None, "Paid"])
    sql.append(insert("Claims",
                      ["claim_id", "serial", "dealer_id", "submitted_date", "repair_date",
                       "operation_code", "claimed_part", "claimed_labour_hours",
                       "goodwill_requested", "status"], rows))
    counts["Claims"] = len(rows)
    claim_ids = {row[0] for row in rows}

    # --- ServiceHistory ----------------------------------------------
    # The repair itself, carrying the part ACTUALLY FITTED. This is the only
    # place the supersession trap can be resolved: the claim says P-44120, the
    # job says P-44120-A.
    rows = []
    n = 0
    for r in records:
        c = r["claim"]
        if c["serial"] not in known:
            continue
        n += 1
        rows.append([f"J-{n:05d}", c["serial"], c["repair_date"], c["op_code"],
                     operations[c["op_code"]]["component"], c["part_fitted"],
                     c["claimed_hours"], c["claim_id"], c["repair_date"]])
        prior = c.get("prior_claim")
        if prior:
            n += 1
            rows.append([f"J-{n:05d}", c["serial"], prior["completed_date"],
                         c["op_code"], prior["component"], c["part_fitted"],
                         c["claimed_hours"], prior["claim_id"], prior["completed_date"]])
    # Every claim a service job cites must exist in the claim system, or the
    # ground truth rests on a record the agent is told does not exist.
    dangling = sorted({row[7] for row in rows if row[7] not in claim_ids})
    if dangling:
        raise ValueError(f"service jobs cite claims missing from Claims: {dangling}")
    sql.append(insert("ServiceHistory",
                      ["job_id", "serial", "job_date", "operation_code", "component",
                       "part_fitted", "labour_hours", "claim_id", "completed_date"], rows))
    counts["ServiceHistory"] = len(rows)

    # --- GoodwillAuthority -------------------------------------------
    rows = [[t["tier"], t["max_amount_inr"], t["approver_role"]]
            for t in ENTITIES["goodwill_authority"]]
    sql.append(insert("GoodwillAuthority",
                      ["tier", "max_amount_inr", "approver_role"], rows))
    counts["GoodwillAuthority"] = len(rows)

    # --- TsbApplicability --- THE STALE TABLE ------------------------
    rows = []
    for b in INSTRUMENTS["bulletins"]:
        if b.get("serial_from") is None:
            continue
        rows.append([b["id"], b["families"][0], b["serial_from"],
                     b.get("index_serial_to", b["serial_to"]),   # <- stale on 0051
                     b["effective_from"],
                     "Superseded" if b.get("superseded_by") else "Current"])
    sql.append(insert("TsbApplicability",
                      ["tsb_id", "family", "serial_from", "serial_to",
                       "effective_from", "status"], rows))
    counts["TsbApplicability"] = len(rows)

    return "\n".join(sql), counts


if __name__ == "__main__":
    NL = chr(10)
    OUT.mkdir(parents=True, exist_ok=True)
    inserts, counts = build()
    statements = [line for line in inserts.splitlines() if line.strip()]

    written = []
    for dialect, suffix in (("sqlite", "sqlite"), ("mssql", "azuresql")):
        ddl = schema(dialect)
        (OUT / f"schema.{suffix}.sql").write_text(ddl, encoding="utf-8")
        sep = NL + "GO" + NL + NL if dialect == "mssql" else NL
        body = batched(statements, dialect)
        (OUT / f"seed.{suffix}.sql").write_text(ddl + sep + body + NL,
                                                encoding="utf-8")
        written += [f"schema.{suffix}.sql", f"seed.{suffix}.sql"]

    db_path = OUT / "contoso.db"
    if db_path.exists():
        db_path.unlink()
    con = sqlite3.connect(db_path)
    con.executescript(schema("sqlite") + NL + inserts)
    con.commit()

    for table, n in counts.items():
        print(f"  {table:20} {n:>6} rows")

    stale = con.execute(
        "SELECT serial_to FROM TsbApplicability WHERE tsb_id='TSB-C-0051'").fetchone()[0]
    doc = next(b["serial_to"] for b in INSTRUMENTS["bulletins"] if b["id"] == "TSB-C-0051")
    con.close()

    print(NL + f"  trap 1 armed: index says TSB-C-0051 ends at {stale}, "
               f"the bulletin document says {doc}")
    print(NL + "  " + ", ".join(written) + ", contoso.db")
    print(NL + f"Written to {OUT}")
